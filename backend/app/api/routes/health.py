"""Health / system endpoints."""
from __future__ import annotations

import time

from fastapi import APIRouter
from sqlalchemy import text

from app.config import settings
from app.core.state_manager import state_manager
from app.ml.inference import model_summary
from app.models.database_setup import engine
from app.models.schemas import HealthResponse

router = APIRouter(tags=["system"])


@router.get("/health", response_model=HealthResponse)
def health() -> HealthResponse:
    """Liveness + dependency check (database reachable, version info)."""
    db_state = "ok"
    try:
        with engine.connect() as conn:
            conn.execute(text("SELECT 1"))
    except Exception as exc:  # pragma: no cover
        db_state = f"error: {exc}"
    return HealthResponse(
        status="ok" if db_state == "ok" else "degraded",
        version=settings.version,
        database=db_state,
        uptime_s=round(time.time() - state_manager.started_at, 1),
        active_simulations=state_manager.active_count(),
    )


@router.get("/system/info")
def system_info() -> dict:
    """Capabilities advertised to the dashboard (no mocked values)."""
    return {
        "name": settings.app_name,
        "full_name": settings.app_full_name,
        "version": settings.version,
        "data_source": "SIMULATED",
        "disclaimer": (
            "All navigation data in GRIDS is generated by a physics-based simulator. "
            "Simulated accuracy does not establish real-world performance."
        ),
        "connected_clients": state_manager.connected_clients,
        "capabilities": {
            "ekf": True,
            "dead_reckoning": True,
            "gnss_anomaly_detection": "statistical (explainable)",
            "map_matching": "offline synthetic road network",
            "ml_correction": model_summary()["available"],
            "websocket": True,
        },
        "limits": {
            "max_duration_s": settings.max_duration_s,
            "max_rate_hz": settings.max_rate_hz,
        },
    }
